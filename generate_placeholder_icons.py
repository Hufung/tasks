#!/usr/bin/env python3
import os

# Create placeholder PNG files (1x1 transparent pixel in PNG format)
# This is a minimal valid PNG file
png_data = bytes([
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,  # PNG signature
    0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,  # IHDR chunk
    0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,  # 1x1 dimensions
    0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4,
    0x89, 0x00, 0x00, 0x00, 0x0A, 0x49, 0x44, 0x41,  # IDAT chunk
    0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00,
    0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00,
    0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE,  # IEND chunk
    0x42, 0x60, 0x82
])

densities = ['mdpi', 'hdpi', 'xhdpi', 'xxhdpi', 'xxxhdpi']

for density in densities:
    dir_path = f'app/src/main/res/mipmap-{density}'
    os.makedirs(dir_path, exist_ok=True)
    
    # Create ic_launcher.png
    with open(f'{dir_path}/ic_launcher.png', 'wb') as f:
        f.write(png_data)
    
    # Create ic_launcher_round.png
    with open(f'{dir_path}/ic_launcher_round.png', 'wb') as f:
        f.write(png_data)
    
    print(f'Created icons for {density}')

print('Placeholder icons created successfully!')
